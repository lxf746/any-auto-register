export function detectLocale(input?: string | null): AppLocale {
  const value = String(input || '').toLowerCase()
  if (value.startsWith('vi')) return 'vi'
  if (value.startsWith('zh')) return 'zh'
  return 'en'
}

export function translate(locale: AppLocale, key: string, vars?: Record<string, string | number>) {
  const template = MESSAGES[locale][key] || MESSAGES[DEFAULT_LOCALE][key] || MESSAGES.zh[key] || key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, token) => String(vars[token] ?? `{${token}}`))
}

export function formatLocaleDate(
  locale: AppLocale,
  value: string | number | Date,
  options?: Intl.DateTimeFormatOptions,
) {
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return '-'
  return new Intl.DateTimeFormat(INTL_LOCALES[locale], options).format(date)
}